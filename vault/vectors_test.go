var update = flag.Bool("update", false, "rewrite testdata/vectors.json")

const vectorsPath = "../testdata/vectors.json"

// Fixed inputs. The password mixes ASCII, a non-ASCII letter and an emoji so both sides prove
// they hash the same UTF-8 bytes.
const (
	vecPassword  = "correct horse battery staple ü 🔑"
	vecIter      = 1000 // far below MinIter: only to keep the Java test fast
	vecKeyringID = "0123456789abcdef"
	vecExportPw  = "export pässword"
)

func seq(start byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

var (
	vecSalt        = seq(0x00, 16)
	vecVK          = seq(0x20, 32)
	vecKeyNonce    = seq(0x40, 12)
	vecEntryNonce  = seq(0x50, 12)
	vecExportSalt  = seq(0x60, 16)
	vecExportNonce = seq(0x70, 12)
	vecStamp       = crdt.Stamp{Wall: 1795121162000, Counter: 0, Device: "dev-a"}
)

func vecOps() []crdt.MapOp {
	s := func(c uint32) crdt.Stamp { return crdt.Stamp{Wall: 1795121162000, Counter: c, Device: "dev-a"} }
	return []crdt.MapOp{
		{Key: "i.3fa91c20d4e5f601.type", Value: json.RawMessage(`"login"`), Stamp: s(0)},
		{Key: "i.3fa91c20d4e5f601.name", Value: json.RawMessage(`"GitHub"`), Stamp: s(1)},
		{Key: "i.3fa91c20d4e5f601.user", Value: json.RawMessage(`"octo@example.com"`), Stamp: s(2)},
		{Key: "i.3fa91c20d4e5f601.pass", Value: json.RawMessage(`"pässwörd <&> \"q\""`), Stamp: s(3)},
		{Key: "i.3fa91c20d4e5f601.urls", Value: json.RawMessage(`["https://github.com/login"]`), Stamp: s(4)},
		{Key: "i.3fa91c20d4e5f601.notes", Delete: true, Stamp: s(5)},
	}
}

// buildVectors computes every vector from the fixed inputs.
func buildVectors(t *testing.T) map[string]any {
	t.Helper()
	mk, err := DeriveKey(vecPassword, vecSalt, vecIter)
	if err != nil {
		t.Fatal(err)
	}
	kr, err := WrapKeyring(vecPassword, vecVK, KeyringParams{ID: vecKeyringID, Salt: vecSalt, Nonce: vecKeyNonce, Iter: vecIter, Stamp: vecStamp})
	if err != nil {
		t.Fatal(err)
	}
	krBody, _ := json.Marshal(kr)
	plain, err := MarshalBatch(vecOps())
	if err != nil {
		t.Fatal(err)
	}
	ent, err := EncryptBatchNonce(vecVK, vecKeyringID, plain, vecEntryNonce)
	if err != nil {
		t.Fatal(err)
	}
	entBody, _ := json.Marshal(ent)
	exportPlain := []byte(`{"raypass":1,"items":[{"id":"3fa91c20d4e5f601","type":"note","name":"Hi","notes":"secret"}]}`)
	ex, err := SealExportWith(vecExportPw, exportPlain, vecIter, vecExportSalt, vecExportNonce)
	if err != nil {
		t.Fatal(err)
	}
	exBody, _ := json.Marshal(ex)

	type tv struct {
		SecretASCII string `json:"secret_ascii,omitempty"`
		URI         string `json:"uri,omitempty"`
		Algorithm   string `json:"algorithm"`
		Digits      int    `json:"digits"`
		Period      int    `json:"period"`
		Time        int64  `json:"time"`
		Code        string `json:"code"`
	}
	var totps []tv
	rfc := []struct {
		alg, secret string
		codes       []string
	}{
		{totp.SHA1, "12345678901234567890", []string{"94287082", "07081804", "14050471", "89005924", "69279037", "65353130"}},
		{totp.SHA256, "12345678901234567890123456789012", []string{"46119246", "68084774", "67062674", "91819424", "90698825", "77737706"}},
		{totp.SHA512, "1234567890123456789012345678901234567890123456789012345678901234", []string{"90693936", "25091201", "99943326", "93441116", "38618901", "47863826"}},
	}
	times := []int64{59, 1111111109, 1111111111, 1234567890, 2000000000, 20000000000}
	for _, r := range rfc {
		for i, tm := range times {
			totps = append(totps, tv{SecretASCII: r.secret, Algorithm: r.alg, Digits: 8, Period: 30, Time: tm, Code: r.codes[i]})
		}
	}
	// URI-driven vectors (6 digits, period 60, Steam). Their codes are computed by this
	// implementation from the RFC algorithm, so they pin URI parsing and Steam's alphabet.
	for _, u := range []string{
		"otpauth://totp/ACME:alice?secret=GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ&issuer=ACME",
		"otpauth://totp/ACME:alice?secret=GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ&algorithm=SHA256&digits=7&period=60",
		"steam://GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ",
	} {
		p, err := totp.Parse(u)
		if err != nil {
			t.Fatal(err)
		}
		code, _ := p.Code(time.Unix(1234567890, 0))
		alg := p.Algorithm
		if p.Steam {
			alg = "STEAM"
		}
		totps = append(totps, tv{URI: u, Algorithm: alg, Digits: p.Digits, Period: p.Period, Time: 1234567890, Code: code})
	}

	return map[string]any{
		"about": "Raypass crypto vectors (design/DESIGN.md \"Crypto\"). Generated by `go test ./vault -run TestVectors -update`; " +
			"checked by the Go tests and the Android Java tests. iter is 1000 here only to keep tests fast: real keyrings use 600000 and " +
			"refuse fewer than 100000. All base64 is standard with padding. Byte strings that are plaintext are given both as a UTF-8 " +
			"string and as base64 of the exact bytes; the *_b64 form is authoritative.",
		"kdf": map[string]any{
			"password":          vecPassword,
			"password_utf8_hex": hex.EncodeToString([]byte(vecPassword)),
			"salt_b64":          B64.EncodeToString(vecSalt),
			"iter":              vecIter,
			"mk_hex":            hex.EncodeToString(mk),
		},
		"keyring": map[string]any{
			"vk_hex":      hex.EncodeToString(vecVK),
			"nonce_b64":   B64.EncodeToString(vecKeyNonce),
			"aad":         AADKeyring,
			"wrapped_b64": kr.Wrapped,
			"check_label": CheckLabel,
			"check_b64":   kr.Check,
			"body":        json.RawMessage(krBody),
		},
		"vault_entry": map[string]any{
			"vk_hex":        hex.EncodeToString(vecVK),
			"keyring_id":    vecKeyringID,
			"nonce_b64":     B64.EncodeToString(vecEntryNonce),
			"aad":           AADVault,
			"plaintext":     string(plain),
			"plaintext_b64": B64.EncodeToString(plain),
			"c_b64":         ent.C,
			"body":          json.RawMessage(entBody),
		},
		"export": map[string]any{
			"password":      vecExportPw,
			"salt_b64":      B64.EncodeToString(vecExportSalt),
			"nonce_b64":     B64.EncodeToString(vecExportNonce),
			"iter":          vecIter,
			"aad":           AADExport,
			"plaintext":     string(exportPlain),
			"plaintext_b64": B64.EncodeToString(exportPlain),
			"file":          json.RawMessage(exBody),
		},
		"totp": totps,
	}
}

func TestVectors(t *testing.T) {
	v := buildVectors(t)
	got, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if *update {
		if err := os.WriteFile(vectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("%v (run go test ./vault -run TestVectors -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("testdata/vectors.json does not match what the code computes")
	}

	// And read the file back the way another implementation would.
	var f struct {
		KDF struct {
			Password string `json:"password"`
			Salt     string `json:"salt_b64"`
			Iter     int    `json:"iter"`
			MK       string `json:"mk_hex"`
		} `json:"kdf"`
		Keyring struct {
			VK   string          `json:"vk_hex"`
			Body json.RawMessage `json:"body"`
		} `json:"keyring"`
		Entry struct {
			Plain string          `json:"plaintext_b64"`
			Body  json.RawMessage `json:"body"`
		} `json:"vault_entry"`
		Export struct {
			Password string          `json:"password"`
			Plain    string          `json:"plaintext_b64"`
			File     json.RawMessage `json:"file"`
		} `json:"export"`
	}
	if err := json.Unmarshal(want, &f); err != nil {
		t.Fatal(err)
	}
	salt, _ := B64.DecodeString(f.KDF.Salt)
	mk, _ := DeriveKey(f.KDF.Password, salt, f.KDF.Iter)
	if hex.EncodeToString(mk) != f.KDF.MK {
		t.Fatal("mk")
	}
	kr, ok := ParseKeyring(f.Keyring.Body)
	if !ok || !kr.Valid(1) {
		t.Fatal("keyring body")
	}
	vk, err := kr.Unwrap(f.KDF.Password)
	if err != nil || hex.EncodeToString(vk) != f.Keyring.VK {
		t.Fatalf("unwrap: %v", err)
	}
	if _, err := kr.Unwrap(f.KDF.Password + " "); err != ErrWrongPassword {
		t.Fatalf("a trailing space must be a different password: %v", err)
	}
	e, ok := ParseEntry(f.Entry.Body)
	if !ok {
		t.Fatal("entry body")
	}
	ops, err := e.Decrypt(vk)
	if err != nil || len(ops) != len(vecOps()) || ops[3].Stamp.Counter != 3 || !ops[5].Delete {
		t.Fatalf("decrypt: %v %+v", err, ops)
	}
	p, err := OpenExport(f.Export.File, f.Export.Password, 1)
	if err != nil || B64.EncodeToString(p) != f.Export.Plain {
		t.Fatalf("export: %v", err)
	}
	if _, err := OpenExport(f.Export.File, f.Export.Password, MinIter); err == nil {
		t.Fatal("an export below MinIter must be refused")
	}
}
